#!/usr/bin/env python3
"""ORACLE-W1: lists the plain `bool` data members of C++ classes so the oracle fixtures can keep them canonical (0/1).

The exe compiles `if (flag)` as `cmp byte [..], 0` in some functions and `cmp byte [..], 1` / `sete` in others; random fixture bytes make a bool 2..255 which is
undefined behaviour for the port and makes the two implementations legitimately differ. The generated table gives, per class, the member offsets via offsetof(), so the
fixture builder can overwrite exactly those bytes with 0/1 after filling the object with garbage.

usage: gen_bool_offsets.py <out.inc> <header>:<Class>[:<DerivedClass>] [...]   (table name kBools_<Class>, or kBools_<Derived>_<Class> when a derived class is given)
Only members declared directly as `bool name;` / `bool name{...};` / `bool name = ...;` / `bool name[N];` at class scope are listed (bit-fields and bools inside nested
structs are not). Run from the repo root; the output is committed (tests/standalone/wave1_oracle_bools.inc).
"""
import re, sys

def members(header, cls):
    src = open(header, encoding='utf-8', errors='replace').read()
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    src = re.sub(r'//[^\n]*', '', src)
    m = re.search(r'\b(?:class|struct)\s+(?:[A-Z_]+\s+)?' + re.escape(cls) + r'\b[^;{]*\{', src)
    if not m:
        raise SystemExit('class %s not found in %s' % (cls, header))
    i = m.end(); depth = 1; body = []
    while depth and i < len(src):
        c = src[i]
        if c == '{': depth += 1
        elif c == '}': depth -= 1
        body.append(c if depth >= 1 else ' ')
        i += 1
    body = ''.join(body)
    # keep only depth-1 text (drop nested braces: function bodies, nested structs, initialisers)
    out = []; d = 0
    for c in body:
        if c == '{': d += 1; continue
        if c == '}': d -= 1; out.append(';'); continue
        if d == 0: out.append(c)
    flat = re.sub(r'(?:public|private|protected)\s*:', ';', ''.join(out))
    res = []
    for stmt in flat.split(';'):
        s = ' '.join(stmt.split())
        mm = re.fullmatch(r'(?:alignas\(\d+\) )?bool (\w+)(?:\[(\w+)\])?(?: = \w+)?', s)
        if mm:
            res.append((mm.group(1), mm.group(2)))
    return res

def main():
    out = sys.argv[1]
    lines = ['// GENERATED by tests/standalone/tools/gen_bool_offsets.py - plain bool data members per class (see the tool); do not edit by hand', '#pragma once', '']
    for spec in sys.argv[2:]:
        parts = spec.split(':')
        header, cls = parts[0], parts[1]
        via = parts[2] if len(parts) > 2 else cls     # offsetof is taken in `via` (a derived class) so inherited members get their offset inside the derived object
        ms = members(header, cls)
        if not ms:
            continue        # no plain bool members: no table
        lines.append('// %s (%s)%s: %d bool members' % (cls, header, '' if via == cls else ' as member of ' + via, len(ms)))
        lines.append('inline const std::pair<size_t, size_t> kBools_%s[] = {' % (via if via != cls else cls).replace('::', '_') + ('' if via == cls else '_' + cls))
        for name, n in ms:
            lines.append('    { offsetof(%s, %s), %s },' % (via, name, n if n else '1'))
        lines.append('};')
        lines.append('')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))

main()
