"""Generates tests/standalone/wave3_oracle_camera_bools.inc: the `bool` data members of CCamera / CCam / CIdleCam (parsed from the headers).
The camera oracle fills TheCamera with garbage; a bool byte that is not 0 / 1 is not a game state (every store in the exe writes 0 / 1) and makes `cmp byte, 1` (exe) and `if (b)` (port) differ.
usage: python -X utf8 -I tests/standalone/tools/gen_w3_cam_bools.py   (run from the repo root)"""
import re

BS = chr(92)
out = ['// GENERATED by tests/standalone/tools/gen_w3_cam_bools.py - bool data members that the camera fixture normalises to 0 / 1']
for hdr, macro in (('source/game_sa/Camera.h', 'W3C_BOOLS_CAMERA'), ('source/game_sa/Cam.h', 'W3C_BOOLS_CAM'), ('source/game_sa/IdleCam.h', 'W3C_BOOLS_IDLE')):
    names = []
    for ln in open(hdr, encoding='utf-8'):
        m = re.match(r'^\s*bool\s+(m_\w+)\s*(\{\s*\})?\s*;', ln)
        if m and m.group(1) not in names:
            names.append(m.group(1))
    out.append('#define %s(X) %s' % (macro, BS))
    out += ['    X(%s) %s' % (n, BS) for n in names]
    out.append('    /* end */')
open('tests/standalone/wave3_oracle_camera_bools.inc', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('ok', len(out))
