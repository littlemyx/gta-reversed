#!/usr/bin/env python3
"""Slice D2 of .notes/DETACH_DATA_PLAN.md: emit the string / name tables of the original data image as C++ literals (dev-time tool, the output is reviewed and
committed; the build never runs it).

  gen_d2_tables.py stats      the eight per-page tStatLine tables of CStats::ConstructStatLine (.data 0x8CD8A0 ...)
  gen_d2_tables.py sections   CShopping::ms_sectionNames (0x8A61D8)
  gen_d2_tables.py peds       CPedModelInfo::m_pPedIds (0x8A6268)
  gen_d2_tables.py vehicles   CVehicleModelInfo::ms_vehicleDescs (0x8A7740) and the 12 tables it points to
  common option: --image <original_data.bin> (default build/StandaloneDetached/bin/original_data.bin, VA 0x858000 = file offset 0)

The generated tables are checked again at run time: a detached build started with NOTSA_VERIFY_GLOBALS compares every D2 table against the image still mapped at the
original addresses (source/standalone/GlobalsVerifyTables.h) and verify_globals.py fails on a mismatch.
"""
import argparse
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BASE = 0x858000


class Img:
    def __init__(self, path):
        self.b = Path(path).read_bytes()

    def u32(self, va):
        return struct.unpack_from("<I", self.b, va - BASE)[0]

    def s16(self, va):
        return struct.unpack_from("<h", self.b, va - BASE)[0]

    def u8(self, va):
        return self.b[va - BASE]

    def cstr(self, va):
        o = va - BASE
        return self.b[o:self.b.index(b"\0", o)].decode("latin1")


def cq(s):
    assert all(32 <= ord(c) < 127 and c not in '"\\' for c in s), s
    return '"%s"' % s


STAT_TABLES = [0x8CD8A0, 0x8CD938, 0x8CD9B0, 0x8CD9D8, 0x8CDA70, 0x8CDAC8, 0x8CDBF8, 0x8CDE08]


def gen_stats(img):
    out = []
    for i, a in enumerate(STAT_TABLES):
        ents, p = [], a
        while True:
            sid = img.s16(p)
            ents.append((sid, img.u8(p + 2), img.u8(p + 3), img.u8(p + 4), img.u8(p + 5)))
            p += 6
            if sid == -99:
                break
        out.append("// 0x%X, %d lines + terminator" % (a, len(ents) - 1))
        out.append("constexpr tStatLine kStatLines%d[] = {" % i)
        for k in range(0, len(ents), 4):
            out.append("    " + " ".join("{ %d, %d, %d, %d, %d }," % e for e in ents[k:k + 4]))
        out.append("};")
        out.append("NOTSA_GLOBAL_VERIFY(0x%X, kStatLines%d);" % (a, i))
        out.append("")
    return "\n".join(out)


def gen_sections(img):
    names = [img.cstr(img.u32(0x8A61D8 + 4 * i)) for i in range(11)]
    return "{{ " + ", ".join(cq(n) for n in names) + " }}"


def assoc_rows(img, a):
    rows = []
    while True:
        name = img.u32(a)
        rows.append((img.cstr(name) if name else None, img.u32(a + 4), img.u32(a + 8)))
        a += 12
        if not name:
            return rows


def row_text(r):
    # RwObjectNameIdAssocation { char* m_pName; uint32 m_dwHierarchyId; uint32 m_dwFlags; }: the names are string literals of a char* member
    nm = "nullptr" if r[0] is None else "const_cast<char*>(%s)" % cq(r[0])
    return "{ %s, %d, 0x%X }" % (nm, r[1], r[2])


def gen_peds(img):
    rows = assoc_rows(img, 0x8A6268)
    # the table has 13 slots; the 13th is the {nullptr, 0, 0} terminator
    assert len(rows) == 13 and rows[-1] == (None, 0, 0), rows[-1]
    return "{\n" + "\n".join("    %s," % row_text(r) for r in rows) + "\n}"


def gen_vehicles(img):
    ptrs = [img.u32(0x8A7740 + 4 * i) for i in range(12)]
    out = ["// GENERATED by tools/standalone/gen_d2_tables.py vehicles from the data image (the 12 component tables behind CVehicleModelInfo::ms_vehicleDescs, 0x8A7740).",
           "// Rows: {frame name, hierarchy id, eVehicleComponentFlags}; every table ends with {nullptr, 0, 0}. Included by VehicleModelInfo.cpp (detached build only).", ""]
    for i, p in enumerate(ptrs):
        rows = assoc_rows(img, p)
        out.append("// [%d] 0x%X: %d components" % (i, p, len(rows) - 1))
        out.append("static RwObjectNameIdAssocation s_VehicleDescs%d[] = {" % i)
        out += ["    %s," % row_text(r) for r in rows]
        out.append("};")
        out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("what", choices=["stats", "sections", "peds", "vehicles"])
    ap.add_argument("--image", default=str(REPO / "build" / "StandaloneDetached" / "bin" / "original_data.bin"))
    a = ap.parse_args()
    img = Img(a.image)
    sys.stdout.write({"stats": gen_stats, "sections": gen_sections, "peds": gen_peds, "vehicles": gen_vehicles}[a.what](img) + "\n")


if __name__ == "__main__":
    main()
