#!/usr/bin/env bash
# Conan dependencies for the PortableLinux preset (native Linux x86_64, clang 23 + libc++) -> build/PortableLinux/generators.
#
# Why not a plain `conan install .`: conanfile.py generate() rewrites ConanPresets.json (included by CMakePresets.json, used by the Windows
# presets) and deletes/re-copies source/libs/imgui. This script runs conan from a scratch copy of conanfile.py, so the repository tree is untouched,
# then keeps only the generators (relocatable: absolute paths into ~/.conan2/p).
#
# usage: tools/portable/conan_install_linux.sh [build_type: Release|Debug]     env: CONAN (default ~/.local/bin/conan), TMPDIR
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
CONAN="${CONAN:-$(command -v conan || echo $HOME/.local/bin/conan)}"
BT="${1:-Release}"
"$CONAN" profile detect --exist-ok >/dev/null
DST="$ROOT/build/PortableLinux/generators"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/portable-conan.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
# CMakePresets.json includes ./ConanPresets.json (gitignored, written by a plain `conan install .`); this script never runs that, so give a fresh checkout an empty stub
[ -f "$ROOT/ConanPresets.json" ] || echo '{ "version": 4, "vendor": { "conan": {} } }' > "$ROOT/ConanPresets.json"
cp "$ROOT/conanfile.py" "$WORK/"
mkdir -p "$WORK/source"
SUDOCONF=True; [ "$(id -u)" = 0 ] && SUDOCONF=False
( cd "$WORK" && "$CONAN" install . -c tools.system.package_manager:sudo=$SUDOCONF -pr:h "$ROOT/conan/profiles/linux-x64.txt" -pr:b default -s build_type="$BT" ${CONAN_EXTRA_ARGS:-} \
      --build=missing -of "$WORK/out" )
GEN="$(find "$WORK/out" -name conan_toolchain.cmake -print -quit | xargs dirname)"
# source/libs/imgui (ImGui SDL3 / DX9 bindings + misc/cpp) is generated by conanfile.generate() into the scratch copy; the game's CMake globs it from the tree, so a fresh checkout takes it from there
if [ ! -d "$ROOT/source/libs/imgui" ] && [ -d "$WORK/source/libs/imgui" ]; then mkdir -p "$ROOT/source/libs"; cp -R "$WORK/source/libs/imgui" "$ROOT/source/libs/imgui"; fi
rm -rf "$DST"; mkdir -p "$(dirname "$DST")"; cp -R "$GEN" "$DST"
# conan_toolchain.cmake / *-config.cmake refer to $WORK only through relative generators dir: verify nothing points into the scratch dir
if grep -rl "$WORK" "$DST" >/dev/null 2>&1; then echo "WARNING: generators reference the scratch dir $WORK" >&2; grep -rl "$WORK" "$DST" >&2; fi
echo "generators: $DST"
