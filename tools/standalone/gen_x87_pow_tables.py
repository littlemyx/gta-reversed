#!/usr/bin/env python3
"""Emit source/game_sa/Core/X87PowTables.inc: the data tables of the exe's SSE2 pow kernel (CRT _CIpow 0x822130 -> 0x829B80 -> body 0x829B99, MSVC libm).
usage: py -X utf8 -I tools/standalone/gen_x87_pow_tables.py <gta_sa_compact.exe> > source/game_sa/Core/X87PowTables.inc"""
import struct, sys
d = open(sys.argv[1], 'rb').read()
pe = struct.unpack_from('<I', d, 0x3c)[0]
nsec = struct.unpack_from('<H', d, pe + 6)[0]; opt = struct.unpack_from('<H', d, pe + 20)[0]
base = struct.unpack_from('<I', d, pe + 24 + 28)[0]
secs = []; o = pe + 24 + opt
for i in range(nsec):
    vs, va, rs, rp = struct.unpack_from('<IIII', d, o + 8); secs.append((va + base, vs, rp, rs)); o += 40
def rd(va, n):
    for v, vs, rp, rs in secs:
        if v <= va < v + max(vs, rs): return d[rp + va - v: rp + va - v + n]
    raise Exception(hex(va))
def table(name, va, count, doc):
    print(f"// {doc} (exe 0x{va:X}, {count} doubles)")
    print(f"inline constexpr uint64_t {name}[{count}] = {{")
    vals = struct.unpack('<%dQ' % count, rd(va, 8 * count))
    for i in range(0, count, 4):
        print("    " + ", ".join(f"0x{v:016X}ull" for v in vals[i:i + 4]) + ",")
    print("};")
print("// GENERATED by tools/standalone/gen_x87_pow_tables.py from gta_sa_compact.exe - do not edit")
table("kPowT1", 0x8884F0, 130, "1/m reciprocal table, first 8 mantissa bits")
table("kPowT2", 0x888900, 260, "-log2 pairs (hi, lo) for T1")
table("kPowT3", 0x889110, 130, "second reciprocal table")
table("kPowT4", 0x889520, 260, "-log2 pairs for T3")
table("kPowT5", 0x889D30, 258, "third reciprocal table")
table("kPowT6", 0x88A540, 514, "-log2 pairs for T5")
table("kPowA", 0x88B550, 2, "exp2 polynomial coefficients A")
table("kPowB", 0x88B560, 2, "exp2 polynomial coefficients B")
table("kPowE2", 0x88B570, 256, "2^(j/128) pairs (hi, lo), j = 0..127")
table("kPowC", 0x88BDB0, 2, "exp2 polynomial coefficients C")
table("kPowD", 0x88BDC0, 2, "exp2 polynomial coefficients D")
