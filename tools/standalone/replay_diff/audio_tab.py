"""Generates rd_audio_tab.h for rd_orig.c (pin bit 128, audio RNG partition): the original-exe address ranges that belong to audio code, derived from the port's hook registry
(RH_Scoped*Install(<fn>, 0xADDR) lines): an address belongs to the registered function with the greatest start <= address, and that function is audio when its source file is under
source/game_sa/Audio/ (or toolsmenu audio). Only the start addresses where the audio flag toggles are emitted.   usage: py -I audio_tab.py <repo> > rd_audio_tab.h"""
import re, sys, glob, os
repo = sys.argv[1]
reg = {}
for f in glob.glob(os.path.join(repo, 'source', '**', '*.cpp'), recursive=True):
    audio = '/audio/' in f.replace(chr(92), '/').lower()
    for ln in open(f, errors='replace'):
        m = re.search(r'RH_Scoped\w*Install\(([^,]+),\s*0x([0-9A-Fa-f]{6})', ln)
        if m: reg[int(m.group(2), 16)] = audio
tog = []; prev = False
for a in sorted(reg):
    if reg[a] != prev: tog.append(a); prev = reg[a]
print('/* generated by audio_tab.py: start addresses where the "address belongs to audio code" flag toggles (first entry: audio starts, second: audio ends, ...) */')
print('static const unsigned g_audio_tab[] = {' + ','.join('0x%X' % a for a in tog) + '};')
print('static const int g_audio_tab_n = %d;' % len(tog))
