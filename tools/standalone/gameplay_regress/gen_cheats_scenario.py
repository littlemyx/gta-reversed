#!/usr/bin/env python3
"""Generate the cheat scenario of the gameplay regression suite for BOTH exes from one list: routes/cheats.txt (run build, `probe:cNN_CODE` lines) and orig/cheats.scn (original exe, inputdrv `cheat:` items).
A subset of tools/standalone/gen_cheats_route.py's 70 cheats: the ones whose ON / OFF branches or side effects were wrong in VT-OVERRIDES (VillagePeople, BeachParty, Ninja, Funhouse: first press = setup, second = clean-up; Dusk), plus the common ones
(weapons, health, wanted up / clear, weather, a spawned vehicle). usage: python -X utf8 -I tools/standalone/gameplay_regress/gen_cheats_scenario.py"""
import os
CODES = {0: 'LXGIWYL', 3: 'HESOYAM', 4: 'OSRBLHH', 5: 'ASNAEB', 6: 'AFZLLQLL', 17: 'AIWPRTON', 40: 'BGLUAWML', 41: 'LIFESABEACH', 44: 'AFPHULTL', 56: 'OFVIAC', 70: 'PRIEBJ', 36: 'BTCDBCB', 24: 'UBHYZHQ'}
# order matters (toggles are pressed twice: setup, then clean-up); the effects of one cheat must not hide the next one's: wanted up then clear first, risky toggles last
ORDER = [3, 0, 4, 5, 6, 56, 56, 36, 24, 17, 44, 44, 70, 70, 40, 40, 41, 41]
here = os.path.dirname(os.path.abspath(__file__))
out = ['# GAMEPLAY REGRESSION: cheats (VT-OVERRIDES): every cheat is typed, 3.5 s later `probe:` logs the state; compared with the original exe\'s state after the same cheat (baseline.json "cheats").',
       '# GENERATED by gen_cheats_scenario.py - do not edit', '#include header_free', 'cmd:snap:cheats_start', 'wait:2000', 'probe:start']
oo = ['# GENERATED by gen_cheats_scenario.py (original exe, inputdrv.exe): same sequence as routes/cheats.txt', '#include orig_header', 'mark:foot_stand', 'cap:30', 'wait:1500']
seen = {}
for n, i in enumerate(ORDER):
    c = CODES[i]
    seen[i] = seen.get(i, 0) + 1
    tag = 'c%d_%s%s' % (i, c, '' if seen[i] == 1 else '_%d' % seen[i])
    out += ['mark:cheat_%d_%s' % (i, c)] + [x for ch in c for x in ('key:' + ch.lower(), 'wait:200')] + ['wait:3500', 'probe:' + tag]
    oo += ['mark:cheat_%d_%s' % (i, c), 'cheat:' + c.lower(), 'wait:3500']
out += ['wait:1000', 'cmd:quit', 'wait:5000']
oo += ['wait:2000']
open(os.path.join(here, 'routes', 'cheats.txt'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
open(os.path.join(here, 'orig', 'cheats.scn'), 'w', encoding='utf-8', newline='\n').write('\n'.join(oo) + '\n')
print(len(ORDER), 'cheat presses')
