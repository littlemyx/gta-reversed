//   cl /nologo /O2 /MT /EHsc msvc_rand_gen.cpp && wine ./msvc_rand_gen.exe > msvc_rand_golden.inc      (tools/portable/run_msvc_rand_test.sh REGEN=1)
// Output = C++ initialisers consumed by tests/portable/msvc_rand_test.cpp. Nothing here is derived from the code under test.
#include <cstdio>
#include <cstdlib>
#include <process.h>
#include <windows.h>

static void dump(const char* name, int n) {
    std::printf("static const int %s[%d] = {", name, n);
    for (int i = 0; i < n; i++) { std::printf("%s%d", i ? "," : "", rand()); if (i % 16 == 15) std::printf("\n"); }
    std::printf("};\n");
}
static unsigned __stdcall worker(void*) { dump("g_thread_first_after_main_srand", 20); return 0; }

int main() {
    std::printf("// generated by tests/portable/msvc_rand_gen.cpp with cl.exe (MSVC CRT, _MSC_VER=%d), RAND_MAX=%d\n", _MSC_VER, RAND_MAX);
    std::printf("static const int g_msvc_rand_max = %d;\n", RAND_MAX);
    // 1) the CRT main thread at startup: holdrand = 1 (nothing called rand before)
    dump("g_seed1", 1000);
    // 2) srand variants
    srand(12345);      dump("g_seed12345", 1000);
    srand(0);          dump("g_seed0", 100);
    srand(0xFFFFFFFFu); dump("g_seedFFFFFFFF", 100);
    srand(0x1234);     dump("g_seed1234", 100);
    srand(1);          dump("g_seed1_again", 20);
    // 3) per-thread state: main thread reseeded and advanced, a NEW thread must still start at seed 1
    srand(777); (void)rand(); (void)rand();
    HANDLE h = (HANDLE)_beginthreadex(nullptr, 0, worker, nullptr, 0, nullptr);
    WaitForSingleObject(h, INFINITE); CloseHandle(h);
    // 4) the main thread's own sequence must NOT have been disturbed by the worker (continues after the 2 values above)
    dump("g_main_after_thread", 10);
    return 0;
}
