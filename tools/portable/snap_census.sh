#!/bin/bash
# snap_census.sh - run the PortableMac native census on a SNAPSHOT of the tree, not on the live checkout.
#
# Why: the checkout is shared with parallel agents. A census runs 15-30 min over one PCH (StdInc.h); a half-edit of any header
# by somebody else invalidates the PCH mid-run and floods the TSV with bogus errors. The snapshot is HEAD plus exactly the files
# you name, so the numbers describe your change only.
#
# usage: tools/portable/snap_census.sh NAME [-f PATH]... [-F LISTFILE] [--ref REV] [--compdb FILE] [--root DIR] [-j N] [--only REGEX]
#   NAME        run name; results in $ROOT/NAME.{tsv,md,log} (ROOT default build/snap_census)
#   -f PATH     overlay the working-tree version of PATH (repo-relative) on the snapshot; a path that no longer exists in the
#               working tree is deleted from the snapshot. Repeatable. Without any -f the snapshot is plain REV.
#   -F LISTFILE same, one path per line
#   --ref REV   base tree (default HEAD)
#   --compdb    compile_commands.json to take the TU list from (default build/PortableMac/compile_commands.json); entries whose
#               file does not exist in the snapshot (untracked files of other agents) are dropped
#   --only REGEX  forwarded to clang_census.py (restrict the TU set)
# The TSV is written with snapshot paths mapped back to repo paths, so tools/portable/r_census.py reads it as is.
# Runs low priority (taskpolicy -b, nice 15). Nothing is left running when it exits. Needs: git, rsync, python3, brew llvm.
set -eu
REPO=$(cd "$(dirname "$0")/../.." && pwd)
NAME=${1:?usage: snap_census.sh NAME [-f PATH]... }; shift
ROOT=$REPO/build/snap_census; REF=HEAD; COMPDB=$REPO/build/PortableMac/compile_commands.json; JOBS=6; ONLY=""; FILES=()
while [ $# -gt 0 ]; do
  case $1 in
    -f) FILES+=("$2"); shift 2;;
    -F) while IFS= read -r l; do [ -n "$l" ] && FILES+=("$l"); done < "$2"; shift 2;;
    --ref) REF=$2; shift 2;;
    --compdb) COMPDB=$2; shift 2;;
    --root) ROOT=$2; shift 2;;
    -j) JOBS=$2; shift 2;;
    --only) ONLY=$2; shift 2;;
    *) echo "unknown arg $1" >&2; exit 2;;
  esac
done
SNAP=$ROOT/snap_$NAME
OUT=$ROOT/out_$NAME
mkdir -p "$ROOT"
rm -rf "$SNAP" "$OUT"
mkdir -p "$SNAP"
cd "$REPO"
# 1. base tree: tracked files of REF (source, tools, tests, CMake files the census scripts may read)
git archive "$REF" source tools tests 2>/dev/null | tar -x -C "$SNAP"
# librw is a submodule: take the checked-out working tree (its pin is what the build uses), without .git
rsync -a --exclude .git vendor/librw/ "$SNAP/vendor/librw/"
# source/libs/imgui is generated by conan (untracked): the TUs that include libs/imgui/... (UIRenderer, BugsDebugModule, SDLWrapper) need it in the snapshot
[ -d source/libs ] && rsync -a source/libs/ "$SNAP/source/libs/"
# other vendor dirs referenced by include paths stay in the real checkout (compdb paths outside source/tools/vendor/librw are not rewritten)
# 2. overlay my files
for f in "${FILES[@]:-}"; do
  [ -z "$f" ] && continue
  if [ -e "$REPO/$f" ]; then mkdir -p "$SNAP/$(dirname "$f")"; cp -p "$REPO/$f" "$SNAP/$f"; else rm -f "$SNAP/$f"; fi
done
# 3. compdb with paths mapped into the snapshot
SNAP=$SNAP REPO=$REPO COMPDB=$COMPDB python3 - <<'PY'
import json, os
S, R, C = os.environ['SNAP'], os.environ['REPO'], os.environ['COMPDB']
d = json.load(open(C))
def rep(s):
    for sub in ('source', 'tools', 'tests', 'vendor/librw'):
        s = s.replace(R + '/' + sub, S + '/' + sub)
    return s
out = []
for e in d:
    f = rep(e['file'])
    if not os.path.exists(f):
        continue
    e['file'] = f; e['command'] = rep(e['command']); e['directory'] = rep(e.get('directory', ''))
    out.append(e)
json.dump(out, open(os.path.join(S, 'compdb.json'), 'w'))
print('compdb: %d of %d entries' % (len(out), len(d)))
PY
cd "$SNAP"
ARGS=(run --mode native --compdb "$SNAP/compdb.json" --out "$OUT" -j "$JOBS")
[ -n "$ONLY" ] && ARGS+=(--only "$ONLY")
echo "census start $(date +%T) snapshot=$SNAP" | tee "$ROOT/$NAME.log"
taskpolicy -b nice -n 15 python3 tools/standalone/clang_census.py "${ARGS[@]}" >> "$ROOT/$NAME.log" 2>&1 || echo "census rc=$?" >> "$ROOT/$NAME.log"
taskpolicy -b nice -n 15 python3 tools/standalone/clang_census_report.py --out "$OUT" --mode native --tsv "$ROOT/$NAME.tsv" > "$ROOT/$NAME.md" 2>&1 || true
# map snapshot paths back to repo paths
sed -i '' "s#$SNAP/#$REPO/#g" "$ROOT/$NAME.tsv" "$ROOT/$NAME.md" 2>/dev/null || true
echo "finished $(date +%T): $ROOT/$NAME.tsv" | tee -a "$ROOT/$NAME.log"
