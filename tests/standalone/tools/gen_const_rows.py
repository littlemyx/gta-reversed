#!/usr/bin/env python3
"""ORACLE-W1: generates exe-oracle rows for the tiny constant-returning virtual overrides (GetTaskType, GetEventType, GetEventPriority, GetLifeTime, ControlSubTask, MakeAbortable ...).

These are 3..12-byte functions in the exe (`mov eax, <const>; ret`) that decide AI behaviour through their constants (task ids, event priorities / lifetimes, "is interruptable").
The port's definition is called NON-virtually on a garbage-filled buffer (`obj->Cls::Fn()`), the exe's function at its address with the same `this`; the return value is compared.

Inputs (all produced by tools/standalone/oracle_coverage.py): sites.json (every RH_Scoped*Install site), the exe, tests/standalone for the "already covered" test.
usage: gen_const_rows.py <repo> <sites.json> <exe> <out.inc> <out.cmake>
A site is taken when: the function name is in SIG, the exe function is tiny and ends in a `ret` with the stack cleanup SIG expects, and no existing oracle file mentions its address.
"""
import json, re, sys, os, glob
from capstone import Cs, CS_ARCH_X86, CS_MODE_32

# fn -> (return kind, [argument C++ types]); the argument values are 0 / nullptr
SIG = {
    'GetTaskType': ('i', []), 'GetEventType': ('i', []), 'GetEventPriority': ('i', []), 'GetLifeTime': ('i', []),
    'GetLocalSoundLevel': ('f', []), 'GetWanderType': ('i', []), 'GetModelType': ('i', []),
    'CanBeInterruptedBySameEvent': ('b', []),
    'ControlSubTask': ('p', ['CPed*']), 'CreateNextSubTask': ('p', ['CPed*']),
    'MakeAbortable': ('b', ['CPed*', 'eAbortPriority', 'const CEvent*']), 'IsInterruptable': ('b', ['const CPed*']),
}

def main():
    repo, sites_json, exe_path, out_inc, out_cmake = sys.argv[1:6]
    sites = json.load(open(sites_json))
    exe = open(exe_path, 'rb').read()
    md = Cs(CS_ARCH_X86, CS_MODE_32)
    tok = re.compile(r'0[xX]([0-9A-Fa-f]{6})\b')
    covered = set()
    for f in glob.glob(os.path.join(repo, 'tests/standalone/*')):
        if os.path.basename(f).startswith('wave1_oracle_consts'):
            continue
        try:
            for m in tok.finditer(open(f, encoding='utf-8', errors='replace').read()):
                covered.add(int(m.group(1), 16))
        except OSError:
            pass
    def ret_imm(va):
        off = va - 0x401000 + 0x400
        pos = va
        for _ in range(8):
            ins = next(md.disasm(exe[off:off + 16], pos), None)
            if ins is None: return None
            if ins.mnemonic == 'ret':
                return int(ins.op_str, 0) if ins.op_str else 0
            if ins.mnemonic in ('call', 'jmp') or ins.mnemonic.startswith('j'): return None
            off += ins.size; pos += ins.size
        return None
    def result_width(va):
        # the exe returns only AL / AX for 1- and 2-byte results (`mov al, imm8`, `movzx eax, byte/word ptr [..]`): the upper bits of EAX are whatever the caller left there
        off = va - 0x401000 + 0x400
        ins = next(md.disasm(exe[off:off + 16], va), None)
        if ins is None: return 4
        if ins.mnemonic == 'mov' and ins.op_str.startswith('al,'): return 1
        if ins.mnemonic == 'movzx' and 'byte ptr' in ins.op_str: return 1
        if ins.mnemonic == 'movzx' and 'word ptr' in ins.op_str: return 2
        return 4
    rows = []; skipped = []
    for s in sites:
        fn = s['fn']
        if fn not in SIG or s['addr'] in covered or not s['cls']: continue
        if s['virt'] is False and fn in ('ControlSubTask',): pass
        kind, args = SIG[fn]
        ri = ret_imm(s['addr'])
        if ri is None or ri != 4 * len(args):
            skipped.append((s['cls'], fn, hex(s['addr']), ri)); continue
        # tiny only: reject bodies that are not a few instructions
        hdr = os.path.join(repo, os.path.splitext(s['file'])[0] + '.h')
        if not os.path.exists(hdr):
            skipped.append((s['cls'], fn, hex(s['addr']), 'no header')); continue
        htxt = open(hdr, encoding='utf-8', errors='replace').read()
        if not re.search(r'^(?:class|struct)\s+(?:[A-Z_]+\s+)?' + re.escape(s['cls']) + r'\b[^;{]*\{', htxt, re.M):
            skipped.append((s['cls'], fn, hex(s['addr']), 'class not in ' + os.path.basename(hdr))); continue
        rows.append((s['cls'], fn, s['addr'], kind, args, s['file'], os.path.splitext(s['file'])[0][len('source/'):] + '.h', result_width(s['addr']) if kind == 'i' else 4))
    rows.sort(key=lambda r: (r[5], r[1]))
    seen = set(); out = []
    out.append('// GENERATED by tests/standalone/tools/gen_const_rows.py (%d rows): constant-returning virtual overrides, port definition (non-virtual call) vs exe; do not edit by hand' % len(rows))
    headers = []
    for r in rows:
        if r[6] not in headers: headers.append(r[6])
    for h in headers: out.append('#include "%s"' % h)
    out.append('')
    out.append('static void TestConsts() {')
    for cls, fn, addr, kind, args, f, h, width in rows:
        call_args = ', '.join(['nullptr' if a.endswith('*') else '(%s)0' % a for a in args])
        exe_types = ', '.join(['void*', 'int'] + [('void*' if a.endswith('*') else 'int') for a in args])
        ret_cpp = {'i': 'int32_t', 'f': 'float', 'b': 'uint8_t', 'p': 'uintptr_t'}[kind]
        port = 'static_cast<%s>(static_cast<%s*>(o)->%s::%s(%s))' % (ret_cpp if kind != 'p' else 'uintptr_t', cls, cls, fn, call_args) if kind != 'p' else 'reinterpret_cast<uintptr_t>(static_cast<%s*>(o)->%s::%s(%s))' % (cls, cls, fn, call_args)
        if kind == 'b':
            port = '(uint8_t)(static_cast<%s*>(o)->%s::%s(%s) ? 1 : 0)' % (cls, cls, fn, call_args)
        exe_call = 'oracle::Fn<%s __fastcall(%s)>(0x%X)' % (ret_cpp, exe_types, addr)
        exe_args = ', '.join(['o', '0'] + [('nullptr' if a.endswith('*') else '0') for a in args])
        exe_val = '%s(%s)' % (exe_call, exe_args)
        if kind == 'b': exe_val = '(uint8_t)(%s ? 1 : 0)' % exe_val
        cmp_k = 'f' if kind == 'f' else 'i'
        if width != 4:
            mask = '0xFF' if width == 1 else '0xFFFF'
            port = '(int32_t)((uint32_t)(%s) & %s)' % (port, mask)
            exe_val = '(int32_t)((uint32_t)(%s) & %s)' % (exe_val, mask)
        out.append('    w1k::Case<%s>("%s::%s 0x%X", [](void* o) { return %s; }, [](void* o) { return %s; });' % (ret_cpp, cls, fn, addr, port, exe_val))
    out.append('}')
    open(out_inc, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    srcs = sorted(set(r[5][len('source/'):] for r in rows))
    open(out_cmake, 'w', encoding='utf-8', newline='\n').write('# GENERATED by tests/standalone/tools/gen_const_rows.py: translation units of the rows in wave1_oracle_consts.inc\nset(W1_CONST_SOURCES\n' + ''.join('    %s\n' % s for s in srcs) + ')\n')
    print(len(rows), 'rows,', len(srcs), 'TUs,', len(skipped), 'skipped')
    for s in skipped[:15]: print('  skipped', s)

main()
